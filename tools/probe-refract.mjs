/**
 * Decisive probe: does `backdrop-filter: url(#svgFilter)` actually displace the
 * backdrop in this Chromium build?
 *
 * This is worth a dedicated tool because the answer cannot be reasoned out.
 * `backdrop-filter` accepts a `<filter-value-list>`, and `url()` is valid in
 * that grammar — but a browser is free to treat an unsupported entry as `none`
 * (or drop the declaration) without any console error. The failure mode is
 * therefore *silent*: the page renders, the backdrop is simply not bent, and
 * the CSS looks correct in devtools. Every "liquid glass" demo on the web that
 * ships to Chromium-only is resting on this one behaviour.
 *
 * The probe rules out the failure modes that would otherwise masquerade as
 * "not supported":
 *   · the map is generated by the SAME `lensMapDataUrl` code the plugin uses,
 *     inlined as a data URI (a URL-referenced feImage silently fails);
 *   · the filter is present in the document before the screenshot;
 *   · the backdrop is vertical stripes, uniform along Y, so two panels at
 *     different Y sit over pixel-identical backdrop;
 *   · the control panel has NO backdrop-filter at all, so the only difference
 *     between the two regions is the filter being probed.
 *
 * Output: a PNG plus a numeric verdict. A horizontal phase shift of the stripes
 * inside the panel is the signal; zero difference means unsupported.
 */
import fs from 'node:fs';
import path from 'node:path';
import { shoot, OUT, browser } from './harness.mjs';

const PAGE = path.join(OUT, 'refract-probe.html');
const SHOT = path.join(OUT, 'refract-probe.png');

const HTML = `<!doctype html>
<html><head><meta charset="utf-8"><style>
  html, body { margin: 0; height: 100%; }
  /* Vertical stripes: the signal is a horizontal phase shift, and because the
     pattern is uniform along Y the two panels sit over identical backdrop. */
  body {
    background-image: repeating-linear-gradient(
      90deg, #000 0 12px, #fff 12px 24px);
  }
  .panel {
    position: absolute;
    left: 180px; width: 320px; height: 160px;
  }
  #control { top: 40px; }
  #target  { top: 260px; backdrop-filter: blur(2px) url(#dsl-refract); }
  #banner {
    position: absolute; left: 0; top: 470px; width: 100%;
    font: 22px monospace; color: #ff0; background: #000;
  }
</style></head>
<body>
  <div class="panel" id="control"></div>
  <div class="panel" id="target"></div>
  <div id="banner"></div>
  <script>
    // Same algorithm as lensMapDataUrl, inlined so this probe cannot drift
    // from the shipped map for any reason other than the map itself.
    function lensMapDataUrl(size) {
      const canvas = document.createElement('canvas');
      canvas.width = size; canvas.height = size;
      const g = canvas.getContext('2d');
      const img = g.createImageData(size, size);
      const d = img.data;
      const bezel = size * 0.3;
      const ramp = (dist) => {
        if (dist >= bezel) return 0;
        const t = 1 - dist / bezel;
        return t * t * (3 - 2 * t);
      };
      for (let y = 0; y < size; y += 1) {
        const dy = Math.round(127 * (ramp(y) - ramp(size - 1 - y)));
        for (let x = 0; x < size; x += 1) {
          const dx = Math.round(127 * (ramp(x) - ramp(size - 1 - x)));
          const i = (y * size + x) * 4;
          d[i] = 128 + dx; d[i + 1] = 128 + dy; d[i + 2] = 128; d[i + 3] = 255;
        }
      }
      g.putImageData(img, 0, 0);
      return canvas.toDataURL('image/png');
    }

    const NS = 'http://www.w3.org/2000/svg';
    const svg = document.createElementNS(NS, 'svg');
    svg.setAttribute('width', '0');
    svg.setAttribute('height', '0');
    svg.style.position = 'absolute';
    const filter = document.createElementNS(NS, 'filter');
    filter.setAttribute('id', 'dsl-refract');
    filter.setAttribute('filterUnits', 'objectBoundingBox');
    filter.setAttribute('x', '-20%'); filter.setAttribute('y', '-20%');
    filter.setAttribute('width', '140%'); filter.setAttribute('height', '140%');
    filter.setAttribute('color-interpolation-filters', 'sRGB');
    const feImage = document.createElementNS(NS, 'feImage');
    feImage.setAttribute('href', lensMapDataUrl(192));
    feImage.setAttribute('preserveAspectRatio', 'none');
    feImage.setAttribute('result', 'map');
    const feDisplace = document.createElementNS(NS, 'feDisplacementMap');
    feDisplace.setAttribute('in', 'SourceGraphic');
    feDisplace.setAttribute('in2', 'map');
    feDisplace.setAttribute('scale', '40');
    feDisplace.setAttribute('xChannelSelector', 'R');
    feDisplace.setAttribute('yChannelSelector', 'G');
    filter.appendChild(feImage);
    filter.appendChild(feDisplace);
    svg.appendChild(filter);
    document.body.appendChild(svg);

    const probed = CSS.supports('backdrop-filter', 'url(#dsl-refract)');
    const parsed = CSS.supports('backdrop-filter', 'blur(2px) url(#dsl-refract)');
    const computed = getComputedStyle(document.getElementById('target')).backdropFilter;
    document.getElementById('banner').textContent =
      'CSS.supports url()=' + probed + '  blur+url=' + parsed + '  computed=' + computed;
  </script>
</body></html>`;

fs.mkdirSync(OUT, { recursive: true });
fs.writeFileSync(PAGE, HTML);
console.log('browser:', browser);

const ok = shoot(PAGE, SHOT, { width: 900, height: 520, budget: 1200 });
console.log('shot:', ok, SHOT);
